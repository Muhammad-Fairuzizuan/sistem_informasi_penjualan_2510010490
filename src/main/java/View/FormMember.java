    private void tbmemberMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbmemberMouseClicked
    int baris = tbmember.getSelectedRow();

    tfidmember.setText(
            tbmember.getValueAt(baris, 0).toString()
    );

    tfalamat.setText(
            tbmember.getValueAt(baris, 1).toString()
    );

    tftelepon.setText(
            tbmember.getValueAt(baris, 2).toString()
    );

    tfemail.setText(
            tbmember.getValueAt(baris, 3).toString()
    );
    
    pathGambar = tbmember.getValueAt(baris, 4).toString();

    tfpath.setText(pathGambar);

    ImageIcon icon = new ImageIcon(
            "Foto_member/" + pathGambar
    );

    Image img = icon.getImage().getScaledInstance(
            lbgambar.getWidth(),
            lbgambar.getHeight(),
            Image.SCALE_SMOOTH
    );

    lbgambar.setIcon(new ImageIcon(img));

    tfnik.setText(
            tbmember.getValueAt(baris, 5).toString()
    );                                                                                                                // TODO add your handling code here:
    }//GEN-LAST:event_tbmemberMouseClicked

