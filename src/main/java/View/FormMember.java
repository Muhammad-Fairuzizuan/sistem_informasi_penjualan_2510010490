    private void btgambarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgambarActionPerformed
    JFileChooser chooser = new JFileChooser();
    int hasil = chooser.showOpenDialog(this);

if (hasil == JFileChooser.APPROVE_OPTION) {

    File file = chooser.getSelectedFile();

    String namaFile = file.getName();

    Path tujuan = Paths.get(
        "Foto_member/" + namaFile
);

        try {
        Files.createDirectories(
                Paths.get("Foto_member")
        );
            
            Files.copy(
                    file.toPath(),
                    tujuan,
                    StandardCopyOption.REPLACE_EXISTING
            );  } catch (IOException ex) {
            System.getLogger(FormMember.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    pathGambar = namaFile;

    tfpath.setText(pathGambar);

    ImageIcon icon =
            new ImageIcon(tujuan.toString());

    Image img = icon.getImage().getScaledInstance(
            lbgambar.getWidth(),
            lbgambar.getHeight(),
            Image.SCALE_SMOOTH
    );

    lbgambar.setIcon(
            new ImageIcon(img)
    );
}// TODO add your handling code here:
    }//GEN-LAST:event_btgambarActionPerformed

